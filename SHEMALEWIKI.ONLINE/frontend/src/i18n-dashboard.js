// Detect the default language: localStorage > domain > default
export function detectDashboardLang() {
  try {
    const saved = typeof localStorage !== 'undefined' && localStorage.getItem('dashboard_lang');
    if (saved && translations[saved]) return saved;
  } catch { /* ignore */ }

  if (typeof window !== 'undefined' && window.location && window.location.hostname) {
    const host = window.location.hostname;
    if (host.includes('buscatrans')) return 'es';
  }
  return 'en';
}

export const SUPPORTED_LANGS = ['en', 'es', 'pt', 'nl', 'fr', 'he'];

export function getDashboardTranslations(lang) {
  return translations[lang] || translations.en;
}

export default translations;
